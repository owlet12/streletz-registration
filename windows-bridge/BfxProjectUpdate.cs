using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace StreletzBridge
{
    // A pure, bounded merge. The caller owns revision/path checks and an atomic
    // new-file save; neither source dictionary nor the active project is changed.
    internal static class BfxProjectUpdate
    {
        private const int MaximumRecords = 100000;
        private static readonly string[] FreshRootFields = {
            "format", "schemaVersion", "transferVersion", "exportedAt", "source", "panels", "panelMappingVersion",
            "panelMappingFingerprint", "panelCatalogComplete", "panelCatalogOrigin", "panelCatalogIssues",
            "unresolvedPanelRecordIds", "panelSource", "panelCatalogNativeFingerprint"
        };
        private static readonly string[] FreshRecordFields = {
            "id", "name", "description", "programmed", "initialized", "version", "zone", "group", "type", "hiddenId",
            "sourceRow", "recordKind", "bfx", "projectPanelId"
        };
        private static readonly string[] StageNames = { "Не начато", "Найдено", "Инициализировано", "Проверено" };

        internal static Dictionary<string, object> Merge(Dictionary<string, object> current, Dictionary<string, object> fresh)
        {
            var oldRows = ValidatedRows(current, "открытого проекта");
            var newRows = ValidatedRows(fresh, "выбранного BFX");
            var oldById = oldRows.ToDictionary(Id, StringComparer.OrdinalIgnoreCase);
            var newById = newRows.ToDictionary(Id, StringComparer.OrdinalIgnoreCase);
            var oldDevices = oldRows.Where(IsDevice).ToArray();
            if (oldDevices.Length == 0)
                throw new InvalidDataException("В открытом проекте нет устройств для сопоставления. Создайте отдельный проект из BFX.");
            int missing = oldDevices.Count(row => !newById.ContainsKey(Id(row)) || !IsDevice(newById[Id(row)]));
            if (missing != 0)
                throw new InvalidDataException("Выбранный BFX не содержит все устройства открытого проекта (отсутствует: " + missing
                    + "). Обновление остановлено; выберите полный исходный BFX с теми же GUID.");

            var result = BridgeValues.Copy(current);
            var source = BridgeValues.Copy(fresh);
            foreach (var field in source) if (!result.ContainsKey(field.Key)) result[field.Key] = field.Value;
            foreach (string field in FreshRootFields)
            {
                object value;
                if (source.TryGetValue(field, out value)) result[field] = value;
                else result.Remove(field);
            }
            if (String.IsNullOrWhiteSpace(BridgeValues.Text(result, "siteName"))) result["siteName"] = BridgeValues.Text(source, "siteName");

            var records = new List<object>();
            foreach (var incoming in newRows)
            {
                Dictionary<string, object> old;
                var row = new Dictionary<string, object>();
                var newest = BridgeValues.Copy(incoming);
                if (oldById.TryGetValue(Id(incoming), out old))
                {
                    row = BridgeValues.Copy(old);
                    foreach (var field in newest) if (!row.ContainsKey(field.Key)) row[field.Key] = field.Value;
                    foreach (string field in FreshRecordFields)
                    {
                        object value;
                        if (newest.TryGetValue(field, out value)) row[field] = value;
                        else row.Remove(field);
                    }
                    if (IsDevice(incoming)) MergeCommissioning(row, old, incoming);
                }
                else row = newest;
                row["id"] = Id(incoming);
                if (IsDevice(row))
                {
                    // Ensure every emitted device has a coherent stage, while
                    // preserving any explicit local description (even empty).
                    var commissioning = Commissioning(row, "результата обновления");
                    int stage = Stage(row, commissioning);
                    if (commissioning == null)
                    {
                        commissioning = new Dictionary<string, object>();
                        row["commissioning"] = commissioning;
                    }
                    commissioning["stage"] = stage;
                    commissioning["stageName"] = StageNames[stage];
                    row["initialized"] = stage >= 2 ? "+" : "-";
                    row["description"] = ProjectPanelCatalog.EffectiveDescription(row);
                }
                records.Add(row);
            }
            // Portable metadata/header rows are not generated by BfxReader.
            // Preserve unmatched non-device rows instead of silently discarding
            // fields or notes outside the supported radio-device list.
            foreach (var old in oldRows.Where(row => !IsDevice(row) && !newById.ContainsKey(Id(row))))
                records.Add(BridgeValues.Copy(old));
            if (records.Count > MaximumRecords) throw new InvalidDataException("Обновлённый проект превышает допустимое число записей.");
            result["records"] = records.ToArray();

            // A BFX catalog is fresh file evidence, never live availability. Its
            // fingerprint must bind to the complete merged GUID set, including
            // any preserved portable metadata rows.
            var panels = (BridgeValues.Array(source, "panels") ?? new object[0]).OfType<Dictionary<string, object>>().Select(BridgeValues.Copy).ToArray();
            if (panels.Length > 0)
            {
                ProjectPanelCatalog.Apply(result, panels);
                result["panelCatalogComplete"] = BridgeValues.Flag(source, "panelCatalogComplete");
            }
            else
            {
                result["panels"] = new object[0];
                result["panelMappingVersion"] = 1;
                result["panelMappingFingerprint"] = BridgeValues.ProjectFingerprint(result);
                result["panelCatalogComplete"] = false;
            }
            RefreshSummary(result, source);
            return result;
        }

        private static void MergeCommissioning(Dictionary<string, object> mergedRow,
            Dictionary<string, object> previous, Dictionary<string, object> incoming)
        {
            var old = Commissioning(previous, "открытого проекта");
            var fresh = Commissioning(incoming, "выбранного BFX");
            int oldStage = Stage(previous, old), freshStage = Stage(incoming, fresh);
            string oldSerial = BridgeValues.Text(old, "serial").Trim();
            string freshSerial = BridgeValues.Text(fresh, "serial").Trim();
            bool conflict = oldSerial.Length > 0 && freshSerial.Length > 0
                && !String.Equals(oldSerial, freshSerial, StringComparison.OrdinalIgnoreCase);
            if (conflict && freshStage >= 2)
                throw new InvalidDataException("У инициализированной записи BFX аппаратный ID отличается от сохранённого журнала (GUID "
                    + Id(previous) + "). Обновление остановлено; сначала выполните ручную сверку этой записи.");
            var merged = fresh == null ? new Dictionary<string, object>() : BridgeValues.Copy(fresh);
            if (old != null)
                foreach (var field in BridgeValues.Copy(old)) merged[field.Key] = field.Value;
            // An explicit nonempty phone serial and every old KEY/note/history
            // field win. Fill only an empty serial from the fresh source.
            if (oldSerial.Length == 0 && freshSerial.Length > 0) merged["serial"] = BridgeValues.Text(fresh, "serial");
            int stage = conflict ? oldStage : Math.Max(oldStage, freshStage);
            merged["stage"] = stage;
            merged["stageName"] = StageNames[stage];
            mergedRow["commissioning"] = merged;
        }

        private static Dictionary<string, object>[] ValidatedRows(Dictionary<string, object> root, string description)
        {
            var rows = BridgeValues.Array(root, "records");
            if (root == null || BridgeValues.Number(root, "schemaVersion") != 1 || rows == null || rows.Length == 0 || rows.Length > MaximumRecords)
                throw new InvalidDataException("Неподдерживаемый или слишком большой состав записей " + description + ".");
            var ids = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var result = new List<Dictionary<string, object>>();
            foreach (object item in rows)
            {
                var row = item as Dictionary<string, object>;
                if (row == null) throw new InvalidDataException("Повреждена запись " + description + ".");
                string id = Id(row);
                if (!ids.Add(id)) throw new InvalidDataException("Повторяется GUID записи " + description + ". Обновление остановлено.");
                if (IsDevice(row)) Stage(row, Commissioning(row, description));
                result.Add(row);
            }
            return result.ToArray();
        }

        private static Dictionary<string, object> Commissioning(Dictionary<string, object> row, string description)
        {
            object value;
            if (!row.TryGetValue("commissioning", out value) || value == null) return null;
            var result = value as Dictionary<string, object>;
            if (result == null) throw new InvalidDataException("Повреждён журнал устройства " + description + ".");
            return result;
        }

        private static int Stage(Dictionary<string, object> row, Dictionary<string, object> commissioning)
        {
            long value = commissioning != null && commissioning.ContainsKey("stage")
                ? BridgeValues.Number(commissioning, "stage", -1) : BridgeValues.Text(row, "initialized") == "+" ? 2 : 0;
            if (value < 0 || value > 3) throw new InvalidDataException("В проекте указан недопустимый этап устройства. Обновление остановлено.");
            return (int)value;
        }

        private static string Id(Dictionary<string, object> row)
        { return BridgeValues.GuidValue(BridgeValues.Text(row, "id"), "запись для обновления BFX"); }
        private static bool IsDevice(Dictionary<string, object> row)
        { return BridgeValues.Text(row, "recordKind") == "device"; }

        private static void RefreshSummary(Dictionary<string, object> result, Dictionary<string, object> fresh)
        {
            var oldSummary = BridgeValues.Object(result, "summary");
            var summary = oldSummary == null ? new Dictionary<string, object>() : BridgeValues.Copy(oldSummary);
            var freshSummary = BridgeValues.Object(fresh, "summary");
            if (freshSummary != null)
                foreach (var field in BridgeValues.Copy(freshSummary)) if (!summary.ContainsKey(field.Key)) summary[field.Key] = field.Value;
            var all = BridgeValues.Array(result, "records");
            var devices = all.OfType<Dictionary<string, object>>().Where(IsDevice).ToArray();
            var groups = new Dictionary<string, object>();
            foreach (var row in devices)
            {
                string group = BridgeValues.Text(row, "group");
                groups[group] = groups.ContainsKey(group) ? (int)groups[group] + 1 : 1;
            }
            summary["total"] = all.Length;
            summary["devices"] = devices.Length;
            summary["initialized"] = devices.Count(row => Stage(row, Commissioning(row, "результата обновления")) >= 2);
            summary["checked"] = devices.Count(row => Stage(row, Commissioning(row, "результата обновления")) >= 3);
            summary["groups"] = groups;
            result["summary"] = summary;
        }
    }
}
